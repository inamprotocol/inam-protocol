class FakeRegistry:
    def __init__(self, receipt, requester_addr=CLIENT):
        self.receipt, self.requester_addr = receipt, requester_addr

    def get_agent(self, did):
        addr = self.requester_addr if did == RECEIPT["agentA"]["id"] else PROVIDER_ADDR
        return {"id": did, "linked": {"erc8004_id": addr}}

    def get_receipt(self, receipt_id):
        if receipt_id != self.receipt["receiptId"]:
            raise InamApiError("GET", "/v1/receipts", 404, {})
