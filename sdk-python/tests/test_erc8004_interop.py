def test_python_builds_the_same_bytes_as_typescript():
    fb = build_erc8004_feedback(RECEIPT, REQUESTER, REGISTRY, 7, created_at="2026-10-03T00:00:00.000Z")
    assert fb["file_text"] == EXPECTED_FILE_TEXT
    assert fb["feedback_hash"] == EXPECTED_FEEDBACK_HASH
    assert fb["args"] == {"agentId": 7, "value": 100, "valueDecimals": 0, "tag1": "inam-receipt", "tag2": "translation.tr-en", "endpoint": "", "feedbackHash": EXPECTED_FEEDBACK_HASH}


def test_refuses_drafts_private_receipts_and_unlinked_requesters():
    with pytest.raises(ValueError, match="finalized"):
        build_erc8004_feedback({**RECEIPT, "status": "draft"}, REQUESTER, REGISTRY, 7)
    with pytest.raises(ValueError, match="participants_only"):
        build_erc8004_feedback({**RECEIPT, "visibility": "participants_only"}, REQUESTER, REGISTRY, 7)
    with pytest.raises(ValueError, match="erc8004_id"):
        build_erc8004_feedback(RECEIPT, {"id": RECEIPT["agentA"]["id"], "linked": {}}, REGISTRY, 7)


def test_python_verifies_a_typescript_built_file():
    check = verify_erc8004_feedback(EXPECTED_FILE_TEXT, EXPECTED_FEEDBACK_HASH, CLIENT, FakeRegistry(RECEIPT), value=100)
    assert check == {"valid": True, "reasons": [], "receipt_id": RECEIPT["receiptId"], "provider_did": RECEIPT["agentB"]["id"], "provider_address": PROVIDER_ADDR}


def test_rejects_replay_tampering_wrong_value_and_disputes():
    other = "0x3333333333333333333333333333333333333333"
    sybil = verify_erc8004_feedback(EXPECTED_FILE_TEXT, EXPECTED_FEEDBACK_HASH, other, FakeRegistry(RECEIPT))
    assert "feedback was not sent from the requester's proven erc8004_id" in sybil["reasons"]

    forged = EXPECTED_FILE_TEXT.replace('"outcome":"success"', '"outcome":"failed"')
    tampered = verify_erc8004_feedback(forged, EXPECTED_FEEDBACK_HASH, CLIENT, FakeRegistry(RECEIPT))
    assert {"feedbackHash does not match the file", "receiptId does not match the receipt content"} <= set(tampered["reasons"])

    wrong = verify_erc8004_feedback(EXPECTED_FILE_TEXT, EXPECTED_FEEDBACK_HASH, CLIENT, FakeRegistry(RECEIPT), value=0)
    assert wrong["reasons"] == ["value 0 does not match receipt outcome success"]

    disputed = verify_erc8004_feedback(EXPECTED_FILE_TEXT, EXPECTED_FEEDBACK_HASH, CLIENT, FakeRegistry({**RECEIPT, "status": "disputed"}))
    assert disputed["reasons"] == ["receipt is disputed in the registry"]
